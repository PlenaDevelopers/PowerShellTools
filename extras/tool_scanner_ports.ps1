# Define a funcao para escanear as portas
function Scan-Port {
    param (
        [string]$TargetHost = "192.0.2.10", # Valor padrao para o host
        [int]$StartPort = 1,
        [int]$EndPort = 65535,
        [int]$Timeout = 1000, # Timeout em milissegundos
        [int]$ShowClosedPorts = 0, # 1 para mostrar portas fechadas, 0 para ocultar
        [int]$SaveToFile = 1 # 1 para salvar em arquivo, 0 para nao salvar
    )

    # Inicia o escaneamento
    Write-PowerToolLine "Alvo" $TargetHost "White"
    Write-PowerToolLine "Portas" "$StartPort a $EndPort" "White"
    # Inicializa uma variavel para armazenar resultados
    $results = @()

    for ($port = $StartPort; $port -le $EndPort; $port++) {
        # Tenta conectar a porta
        $tcpClient = New-Object System.Net.Sockets.TcpClient

        try {
            # Conecta a porta especificada
            $tcpClient.Connect($TargetHost, $port)
            # Se a conexao for bem-sucedida, a porta esta aberta
            Write-PowerToolLine "Porta $port" "Aberta" "Green"
        } catch {
            # Se houver um erro, a porta esta fechada ou inativa
            if ($ShowClosedPorts -eq 1) {
                Write-PowerToolLine "Porta $port" "Fechada" "Red"
            }
